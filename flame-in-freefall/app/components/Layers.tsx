import type { ReactNode } from "react";

// The three content layers. Each has a colour AND a text label AND a symbol,
// so colour is never the only signal. Use these everywhere layer content is shown.

interface LayerProps {
  children: ReactNode;
  /** Optional heading shown after the layer label, e.g. "Finding". */
  title?: string;
  className?: string;
}

const STYLES = {
  nasa: {
    box: "border-blue-600 bg-blue-50",
    badge: "bg-blue-700 text-white",
    symbol: "◆",
    label: "NASA found",
    note: "From the NASA source",
  },
  ours: {
    box: "border-orange-500 bg-orange-50",
    badge: "bg-orange-700 text-white",
    symbol: "▲",
    label: "Our safety reading",
    note: "Team interpretation — not NASA guidance",
  },
  ai: {
    box: "border-purple-600 bg-purple-50",
    badge: "bg-purple-700 text-white",
    symbol: "●",
    label: "AI explanation",
    note: "Generated by a local AI — may contain errors, not NASA guidance",
  },
} as const;

export type LayerKind = keyof typeof STYLES;

export function LayerBadge({ kind }: { kind: LayerKind }) {
  const s = STYLES[kind];
  return (
    <span className={`inline-flex items-center gap-1 rounded px-2 py-0.5 text-xs font-bold uppercase tracking-wide ${s.badge}`}>
      <span aria-hidden="true">{s.symbol}</span>
      {s.label}
    </span>
  );
}

function Layer({ kind, children, title, className = "" }: LayerProps & { kind: LayerKind }) {
  const s = STYLES[kind];
  return (
    <section aria-label={title ? `${s.label}: ${title}` : s.label} className={`rounded-md border-l-8 p-4 ${s.box} ${className}`}>
      <div className="mb-2 flex flex-wrap items-center gap-2">
        <LayerBadge kind={kind} />
        {title && <h2 className="text-base font-semibold text-neutral-900">{title}</h2>}
        <span className="text-xs text-neutral-600">{s.note}</span>
      </div>
      <div className="text-neutral-900">{children}</div>
    </section>
  );
}

export function NasaFound(props: LayerProps) {
  return <Layer kind="nasa" {...props} />;
}

export function OurReading(props: LayerProps) {
  return <Layer kind="ours" {...props} />;
}

export function AiExplanation(props: LayerProps) {
  return <Layer kind="ai" {...props} />;
}
